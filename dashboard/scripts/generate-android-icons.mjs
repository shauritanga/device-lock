/**
 * Regenerates the Android apps' icon drawables from Hugeicons (the same icon set
 * the web dashboards use), so web and mobile share one icon language.
 *
 *   cd dashboard && node scripts/generate-android-icons.mjs
 *
 * Each target keeps its existing file name and colour, so layouts and tints are
 * untouched. The launcher icon (brand logo) is not generated.
 */
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const icons = require('@hugeicons/core-free-icons');
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');

// app -> drawable file -> Hugeicons name
const TARGETS = {
  'android-dpc': {
    ic_nav_home: 'Home01Icon',
    ic_nav_payments: 'Wallet01Icon',
    ic_nav_profile: 'UserIcon',
    ic_nav_support: 'HeadphonesIcon',
    ic_notification: 'Notification01Icon',
  },
  'android-collector': {
    ic_arrow_back: 'ArrowLeft02Icon',
    ic_case_list: 'ListViewIcon',
    ic_check: 'Tick02Icon',
    ic_chevron_down: 'ArrowDown01Icon',
    ic_clock: 'Clock01Icon',
    ic_filter: 'FilterHorizontalIcon',
    ic_message_square: 'Message02Icon',
  },
};

const STROKE = 1.8; // a touch heavier than the web's 1.5 so small mobile icons stay legible
const n = (v) => Number(v);
const f = (v) => String(Math.round(v * 1000) / 1000);

/** Convert the few SVG shapes Hugeicons uses into VectorDrawable path data. */
function toPathData(tag, a) {
  if (tag === 'path') return a.d;
  if (tag === 'circle') {
    const [cx, cy, r] = [n(a.cx), n(a.cy), n(a.r)];
    return `M${f(cx - r)},${f(cy)}a${f(r)},${f(r)} 0,1 0,${f(2 * r)},0a${f(r)},${f(r)} 0,1 0,${f(-2 * r)},0`;
  }
  if (tag === 'ellipse') {
    const [cx, cy, rx, ry] = [n(a.cx), n(a.cy), n(a.rx), n(a.ry)];
    return `M${f(cx - rx)},${f(cy)}a${f(rx)},${f(ry)} 0,1 0,${f(2 * rx)},0a${f(rx)},${f(ry)} 0,1 0,${f(-2 * rx)},0`;
  }
  if (tag === 'rect') {
    const [x, y, w, h] = [n(a.x ?? 0), n(a.y ?? 0), n(a.width), n(a.height)];
    const rx = Math.min(n(a.rx ?? a.ry ?? 0), w / 2);
    const ry = Math.min(n(a.ry ?? a.rx ?? 0), h / 2);
    if (!rx && !ry) return `M${f(x)},${f(y)}h${f(w)}v${f(h)}h${f(-w)}z`;
    return `M${f(x + rx)},${f(y)}h${f(w - 2 * rx)}a${f(rx)},${f(ry)} 0,0 1 ${f(rx)},${f(ry)}v${f(h - 2 * ry)}a${f(rx)},${f(ry)} 0,0 1 ${f(-rx)},${f(ry)}h${f(-(w - 2 * rx))}a${f(rx)},${f(ry)} 0,0 1 ${f(-rx)},${f(-ry)}v${f(-(h - 2 * ry))}a${f(rx)},${f(ry)} 0,0 1 ${f(rx)},${f(-ry)}z`;
  }
  throw new Error(`Unsupported shape <${tag}>`);
}

/** Keep the colour the old drawable used (stroke colour, else its fill colour). */
function existingColor(xml) {
  const stroke = xml.match(/android:strokeColor="([^"]+)"/)?.[1];
  if (stroke) return stroke;
  const fill = [...xml.matchAll(/android:fillColor="([^"]+)"/g)]
    .map((m) => m[1])
    .find((c) => !c.includes('transparent'));
  return fill ?? '#111827';
}

for (const [app, files] of Object.entries(TARGETS)) {
  for (const [file, name] of Object.entries(files)) {
    const data = icons[name];
    if (!data) throw new Error(`Hugeicons has no ${name}`);
    const path = resolve(root, app, 'app/src/main/res/drawable', `${file}.xml`);
    const color = existingColor(readFileSync(path, 'utf8'));
    const paths = data
      .map(([tag, a]) => {
        const cap = a.strokeLinecap ?? 'round';
        const join = a.strokeLinejoin ?? 'round';
        return `    <path
        android:fillColor="@android:color/transparent"
        android:pathData="${toPathData(tag, a)}"
        android:strokeColor="${color}"
        android:strokeWidth="${STROKE}"
        android:strokeLineCap="${cap === 'square' ? 'square' : cap}"
        android:strokeLineJoin="${join}" />`;
      })
      .join('\n');
    const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Hugeicons ${name} (MIT) — generated by dashboard/scripts/generate-android-icons.mjs -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
${paths}
</vector>
`;
    writeFileSync(path, xml);
    console.log(`${app}/${file}.xml  <-  ${name}  (${color})`);
  }
}
